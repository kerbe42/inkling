#!/usr/bin/env python3
"""Generate diacritics.h: Latin letters with marks -> (ASCII base, mark, mark2), so handwritten replies can draw
accented letters with the Hershey fonts (base glyph + marks drawn on top). From Python's unicodedata."""
import pathlib, unicodedata
MARKS = {0x300: 'GRAVE', 0x301: 'ACUTE', 0x302: 'CIRC', 0x303: 'TILDE', 0x304: 'MACRON', 0x306: 'BREVE', 0x307: 'DOT',
         0x308: 'DIAER', 0x30A: 'RING', 0x30B: 'DACUTE', 0x30C: 'CARON', 0x327: 'CEDIL', 0x328: 'OGONEK'}
rows = []
ranges = list(range(0xC0, 0x180)) + list(range(0x1CD, 0x1DD)) + list(range(0x1E00, 0x1F00))
for cp in ranges:
    ch = chr(cp)
    d = unicodedata.normalize('NFD', ch)
    if len(d) < 2 or not ('A' <= d[0] <= 'Z' or 'a' <= d[0] <= 'z'):
        continue
    marks = [MARKS.get(ord(m)) for m in d[1:]]
    if None in marks or len(marks) > 2:
        continue
    rows.append((cp, d[0], marks[0], marks[1] if len(marks) > 1 else 'NONE'))
special = [(0xDF, 'ss', 'NONE', 'NONE'), (0xE6, 'ae', 'NONE', 'NONE'), (0xC6, 'AE', 'NONE', 'NONE'), (0x153, 'oe', 'NONE', 'NONE'),
           (0x152, 'OE', 'NONE', 'NONE'), (0xF8, 'o', 'SLASH', 'NONE'), (0xD8, 'O', 'SLASH', 'NONE'), (0x142, 'l', 'STROKE', 'NONE'),
           (0x141, 'L', 'STROKE', 'NONE'), (0x111, 'd', 'BAR', 'NONE'), (0x110, 'D', 'BAR', 'NONE'), (0x131, 'i', 'NODOT', 'NONE'),
           (0xBF, '?', 'ROT', 'NONE'), (0xA1, '!', 'ROT', 'NONE'), (0xAB, '<<', 'NONE', 'NONE'), (0xBB, '>>', 'NONE', 'NONE')]
have = {r[0] for r in rows}
rows += [s for s in special if s[0] not in have]
rows.sort()
out = ['/* Generated by gen_diacritics.py (Unicode decompositions). Do not edit. */', '#ifndef DIACRITICS_H', '#define DIACRITICS_H',
       'enum { M_NONE, M_GRAVE, M_ACUTE, M_CIRC, M_TILDE, M_MACRON, M_BREVE, M_DOT, M_DIAER, M_RING, M_DACUTE, M_CARON, M_CEDIL,',
       '       M_OGONEK, M_SLASH, M_STROKE, M_BAR, M_NODOT, M_ROT };',
       'typedef struct { unsigned short cp; const char *base; unsigned char m1, m2; } Diacritic;',
       'static const Diacritic DIACRITICS[] = {']
for cp, base, m1, m2 in rows:
    out.append('\t{ 0x%04X, "%s", M_%s, M_%s }, /* %s */' % (cp, base, m1, m2, unicodedata.name(chr(cp), '?').lower()))
out += ['};', '#define NDIACRITICS ((int)(sizeof DIACRITICS / sizeof DIACRITICS[0]))', '#endif', '']
pathlib.Path(__file__).with_name('diacritics.h').write_text('\n'.join(out))
print(len(rows), 'letters')
